test('db: Convex, PocketBase, Appwrite, TLS disabled', () => {
  const r = runDatabaseChecks(ctx({
    'package.json': pkg({ convex: '^1', 'node-appwrite': '^14' }),
    'convex/posts.ts': 'export const remove = mutation({ handler: async (ctx, { id }) => ctx.db.delete(id) });',
    'convex/safe.ts': 'export const add = mutation({ handler: async (ctx) => { const i = await ctx.auth.getUserIdentity(); } });',
    'convex/_generated/api.ts': 'export const x = mutation(',
    'pb_migrations/1_init.js': 'collection.listRule = ""\ncollection.deleteRule = ""\ncollection.updateRule = null',
    'src/server/appwrite.ts': 'Permission.write(Role.any())',
    'src/db.ts': 'new Pool({ connectionString: "postgres://u:p@prod.db.io/app?sslmode=disable" })',
  }));
  assert.deepEqual(r.filter((x) => x.id === 'db/convex-public-mutation').map((x) => x.file), ['convex/posts.ts']);
  const pb = r.filter((x) => x.id === 'db/pocketbase-open-rule');
  assert.deepEqual(pb.map((x) => x.severity), ['medium', 'high']);
  assert.ok(ids(r).includes('db/appwrite-public-write'));
  assert.ok(ids(r).includes('db/ssl-disabled'));
});

