const PALETTE: Record<string, Record<string, string>> = {
  gray: { 50: '#f9fafb', 100: '#f3f4f6', 200: '#e5e7eb', 300: '#d1d5db', 400: '#9ca3af', 500: '#6b7280', 600: '#4b5563', 700: '#374151', 800: '#1f2937', 900: '#111827', 950: '#030712' },
  slate: { 50: '#f8fafc', 100: '#f1f5f9', 200: '#e2e8f0', 300: '#cbd5e1', 400: '#94a3b8', 500: '#64748b', 600: '#475569', 700: '#334155', 800: '#1e293b', 900: '#0f172a', 950: '#020617' },
  zinc: { 50: '#fafafa', 100: '#f4f4f5', 200: '#e4e4e7', 300: '#d4d4d8', 400: '#a1a1aa', 500: '#71717a', 600: '#52525b', 700: '#3f3f46', 800: '#27272a', 900: '#18181b', 950: '#09090b' },
  neutral: { 50: '#fafafa', 100: '#f5f5f5', 200: '#e5e5e5', 300: '#d4d4d4', 400: '#a3a3a3', 500: '#737373', 600: '#525252', 700: '#404040', 800: '#262626', 900: '#171717', 950: '#0a0a0a' },
  stone: { 50: '#fafaf9', 100: '#f5f5f4', 200: '#e7e5e4', 300: '#d6d3d1', 400: '#a8a29e', 500: '#78716c', 600: '#57534e', 700: '#44403c', 800: '#292524', 900: '#1c1917', 950: '#0c0a09' },
  yellow: { 100: '#fef9c3', 200: '#fef08a', 300: '#fde047', 400: '#facc15' },
};

function tailwindHex(token: string): string | undefined {
  if (token === 'white') return '#ffffff';
  if (token === 'black') return '#000000';
  const [name, shade] = token.split('-');
  return PALETTE[name]?.[shade];
}

function luminance(hex: string): number {
  const [r, g, b] = [1, 3, 5].map((i) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrastRatio(a: string, b: string): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

/** Class strings in JSX/HTML/Vue/Svelte: className="..", class="..", className={`..`}, cn("..") etc. */
const CLASS_ATTR = /\b(?:className|class)\s*=\s*(?:"([^"]*)"|'([^']*)'|\{\s*`([^`]*)`)/g;

/* ---------------- Rules ---------------- */

const BOILERPLATE = /Create Next App|Generated by create next app|Get started by editing|Edit\s+(<code>)?src\/App\.[jt]sx?(<\/code>)?\s+and save to (reload|test HMR)|Vite \+ React|Click on the Vite and React logos|Welcome to Next\.js|Learn React/;
const PLACEHOLDER = /lorem ipsum|dolor sit amet|\bYour Company\b|\bCompany Name\b|\bAcme (Inc|Corp|Co)\b|\b(John|Jane) Doe\b|\bExample User\b/i;
const LOCALHOST = /['"`]https?:\/\/(localhost|127\.0\.0\.1)(:\d+)?/;
const GENERIC_FONTS = new Set(['sans-serif', 'serif', 'monospace', 'system-ui', 'ui-sans-serif', 'ui-serif', 'ui-monospace', 'inherit', 'initial', 'cursive', 'emoji', '-apple-system', 'blinkmacsystemfont', 'segoe ui', 'apple color emoji', 'segoe ui emoji', 'helvetica', 'arial', 'var']);

function htmlEntries(ctx: ProjectContext): SourceFile[] {
  return ctx.find(/(^|\/)(index|app)\.html$/).filter((f) => !/(^|\/)(public|static|dist|build)\//.test(f.rel) || /^(public\/)?index\.html$/.test(f.rel));
}

/**
 * "UI & Content": things that make an app look unfinished, break on phones, or shut out
 * keyboard and low-vision users. Everything here is a warning: none of it is a security hole.
 */
export function runUiChecks(ctx: ProjectContext): CheckResult[] {
  const markup = ctx.code.filter((f) => MARKUP_EXT.test(f.rel)).concat(htmlEntries(ctx).filter((f) => !ctx.code.includes(f)));
  if (markup.length === 0) {
    return [info('ui/not-applicable', 'No frontend files found, skipping UI & content checks')];
  }

  const results: CheckResult[] = [];
  const isNext = ctx.hasDependency('next');
  const styles = ctx.find(STYLE_EXT).filter((f) => !/(^|\/)(vendor|dist|build)\//.test(f.rel));

  // --- Content left over from templates ---
  const boiler = ctx.grep(markup.concat(ctx.code.filter((f) => /layout\.[jt]sx?$/.test(f.rel))), BOILERPLATE, { literals: true });
  results.push(...capped('content/boilerplate', 'medium', 'Starter template text is still in the app', 'Replace the framework starter content with your own copy and title.', boiler.map((m) => ({ file: m.file, line: m.line, snippet: m.text, detail: `"${m.match[0]}"` }))));

  const placeholder = ctx.grep(markup, PLACEHOLDER, { literals: true });
  results.push(...capped('content/placeholder-text', 'medium', 'Placeholder text in the UI', 'Replace lorem ipsum and placeholder names with real copy before launch.', placeholder.map((m) => ({ file: m.file, line: m.line, snippet: m.text, detail: `"${m.match[0]}"` }))));

  const deadLinks = ctx.grep(markup, /<a\b[^>]*\bhref\s*=\s*["'](#|javascript:void\(0\);?)?["']/, { literals: true });
  results.push(...capped('content/dead-link', 'low', 'Link goes nowhere (href="#")', 'Point it at a real page, or use a <button> if it triggers an action.', deadLinks.map((m) => ({ file: m.file, line: m.line, snippet: m.text }))));

  // Tool/test configs (playwright, vite dev proxy, ...) and scripts point at localhost on purpose.
  const appCode = ctx.code.filter((f) => !/(^|\/)[\w.-]+\.config\.[cm]?[jt]s$|(^|\/)(scripts|tools|e2e)\//.test(f.rel));
  const localhost = ctx.grep(appCode, LOCALHOST, { literals: true }).filter((m) => !/process\.env|import\.meta\.env|\?\?|\|\||emulator/i.test(m.text));
  results.push(...capped('content/localhost-url', 'medium', 'Hardcoded localhost URL will break in production', 'Read the base URL from an environment variable, or use a relative path like "/api/...".', localhost.map((m) => ({ file: m.file, line: m.line, snippet: m.text }))));

  const debuggers = ctx.grep(ctx.code, /^\s*debugger\s*;?\s*$/);
  const consoleLogs = ctx.grep(ctx.code.filter((f) => isClientFile(ctx, f)), /\bconsole\.log\s*\(/);
  results.push(...capped('content/debug-leftovers', 'low', 'Debug code left in client-side code', 'Remove debugger statements and console.log calls (or strip them in your bundler config).', [...debuggers, ...consoleLogs].map((m) => ({ file: m.file, line: m.line, snippet: m.text }))));

  // --- Accessibility that also reads as "broken UI" ---
  const missingAlt: Array<{ file: string; line: number; snippet: string }> = [];
  for (const f of markup) {
    for (const m of f.content.matchAll(/<(img|Image)\b(?:[^>"'{]|"[^"]*"|'[^']*'|\{[^}]*\})*?\/?>/g)) {
      if (/\balt\s*=/.test(m[0]) || /\{\s*\.\.\./.test(m[0])) continue;
      const line = lineAt(f, m.index!);
      if (ctx.isSuppressed(f, line)) continue;
      missingAlt.push({ file: f.rel, line, snippet: m[0].replace(/\s+/g, ' ').slice(0, 120) });
    }
  }
  results.push(...capped('a11y/img-alt', 'medium', 'Image without alt text', 'Add alt="what the image shows" (or alt="" for purely decorative images).', missingAlt));

  const focusHidden: Array<{ file: string; line: number; snippet: string }> = [];
  const lowContrast: Array<{ file: string; line: number; snippet: string; detail: string }> = [];
  const fixedWidth: Array<{ file: string; line: number; snippet: string }> = [];
  for (const f of markup) {
    for (const m of f.content.matchAll(CLASS_ATTR)) {
      const cls = (m[1] ?? m[2] ?? m[3] ?? '').split(/\s+/).filter(Boolean);
      const line = lineAt(f, m.index!);
      if (ctx.isSuppressed(f, line)) continue;
      const snippet = m[0].slice(0, 140);

      if (cls.includes('outline-none') && !cls.some((c) => /^focus(-visible|-within)?:(ring|outline|border|shadow|bg|underline)/.test(c))) {
        focusHidden.push({ file: f.rel, line, snippet });
      }

      const plain = cls.filter((c) => !c.includes(':'));
      const text = plain.map((c) => c.match(/^text-([a-z]+(?:-\d{2,3})?)$/)?.[1]).find((t) => t && tailwindHex(t));
      const bg = plain.map((c) => c.match(/^bg-([a-z]+(?:-\d{2,3})?)$/)?.[1]).find((t) => t && tailwindHex(t));
      if (text && bg) {
        const ratio = contrastRatio(tailwindHex(text)!, tailwindHex(bg)!);
        if (ratio < 3) lowContrast.push({ file: f.rel, line, snippet, detail: `text-${text} on bg-${bg} is ${ratio.toFixed(1)}:1` });
      }

      const wide = plain.find((c) => {
        const px = c.match(/^(?:w|min-w)-\[(\d+)px\]$/)?.[1];
        return px !== undefined && Number(px) >= 640;
      });
      if (wide) fixedWidth.push({ file: f.rel, line, snippet: wide });
    }
  }
  results.push(...capped('a11y/focus-hidden', 'medium', 'Focus outline removed with no replacement: keyboard users can\'t see where they are', 'Add a visible focus style, e.g. focus-visible:ring-2.', focusHidden));
  results.push(...capped('ui/low-contrast', 'medium', 'Text is hard to read', 'Aim for at least 4.5:1 for body text (3:1 for large text). Darken the text or lighten the background.', lowContrast));
  results.push(...capped('ui/fixed-width', 'low', 'Fixed width wider than a phone screen causes sideways scrolling', 'Use max-w-[...] with w-full, or apply the width only from a breakpoint (md:w-[...]).', fixedWidth));

  // --- Page shell: viewport, title, description, favicon, link previews ---
  const html = htmlEntries(ctx);
  for (const f of html) {
    const viewport = f.content.match(/<meta[^>]+name=["']viewport["'][^>]*>/i)?.[0];
    if (!viewport) {
      results.push(warn('ui/viewport', 'high', 'No viewport meta tag: phones render the desktop layout zoomed out', { file: f.rel, fix: 'Add <meta name="viewport" content="width=device-width, initial-scale=1" /> to <head>.' }));
    } else if (/user-scalable\s*=\s*(no|0)|maximum-scale\s*=\s*1(\.0)?\b/i.test(viewport)) {
      results.push(warn('ui/viewport-zoom', 'low', 'Viewport disables pinch-zoom, which low-vision users rely on', { file: f.rel, fix: 'Remove user-scalable=no and maximum-scale=1.' }));
    }
  }

  const titleSources = [...html, ...ctx.code.filter((f) => /(^|\/)(app|src\/app)\/layout\.[jt]sx?$|(^|\/)pages\/_(app|document)\.[jt]sx?$/.test(f.rel))];
  const allHead = titleSources.map((f) => f.content).join('\n');
  if (titleSources.length > 0 || isNext) {
    const hasTitle = /<title>\s*[^<\s][^<]*<\/title>|\btitle\s*:\s*[^\s,}]|<Head>[\s\S]*<title/.test(allHead);
    const hasDescription = /name=["']description["']|\bdescription\s*:\s*[^\s,}]/.test(allHead);
    if (!hasTitle) results.push(warn('content/page-title', 'low', 'No page title: browser tabs and search results show the URL instead', { fix: isNext ? 'Export `metadata = { title: "..." }` from app/layout.tsx.' : 'Add a <title> to index.html.' }));
    if (!hasDescription) results.push(warn('content/meta-description', 'low', 'No meta description: search results and link previews show random page text', { fix: isNext ? 'Add `description` to the metadata export in app/layout.tsx.' : 'Add <meta name="description" content="..."> to index.html.' }));
  }

  const hasFavicon = ctx.allPaths.some((p) => /(^|\/)(public|static|app|src\/app)\/(favicon\.(ico|svg|png)|icon\.(ico|svg|png|tsx?|jsx?))$/.test(p) || /^favicon\.(ico|svg|png)$/.test(p))
    || /rel=["'](shortcut )?icon["']|\bicons\s*:/.test(allHead);
  if (!hasFavicon) results.push(warn('ui/favicon', 'low', 'No favicon: the browser tab shows a blank icon', { fix: 'Add public/favicon.svg (or app/icon.png in Next.js).' }));

  const hasOg = ctx.allPaths.some((p) => /opengraph-image\.(png|jpe?g|tsx?|jsx?)$/.test(p)) || /og:image|openGraph\s*:/.test(allHead);
  if (!hasOg) results.push(warn('ui/og-image', 'low', 'No link preview image: shared links on Slack, X or WhatsApp look bare', { fix: isNext ? 'Add app/opengraph-image.png (1200x630).' : 'Add <meta property="og:image" content="https://.../og.png">.' }));

  // --- Visual consistency ---
  const fonts = new Set<string>();
  for (const f of [...ctx.code, ...styles, ...html]) {
    for (const m of f.content.matchAll(/import\s*\{([^}]+)\}\s*from\s*['"]next\/font\/google['"]/g)) m[1].split(',').forEach((n) => n.trim() && fonts.add(n.trim().replace(/_/g, ' ').toLowerCase()));
    for (const m of f.content.matchAll(/fonts\.googleapis\.com\/css2?\?([^"'\s)]+)/g)) for (const fam of m[1].matchAll(/family=([^:&]+)/g)) fonts.add(decodeURIComponent(fam[1]).replace(/\+/g, ' ').toLowerCase());
    for (const m of f.content.matchAll(/font-family\s*:\s*([^;}\n]+)/g)) {
      const first = m[1].split(',')[0].trim().replace(/['"]/g, '').toLowerCase();
      if (first && !GENERIC_FONTS.has(first) && !first.startsWith('var(')) fonts.add(first);
    }
  }
  if (fonts.size > 3) {
    results.push(warn('ui/font-sprawl', 'low', `${fonts.size} font families (${[...fonts].slice(0, 6).join(', ')}): the UI will look inconsistent`, { fix: 'Pick one family for text and at most one for headings or code.' }));
  }

  const colors = new Set<string>();
  for (const f of markup) {
    if (/(theme|tokens?|colors?|tailwind\.config)/i.test(f.rel)) continue;
    for (const m of f.content.matchAll(/#(?:[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b(?![0-9a-fA-F-])/g)) colors.add(m[0].toLowerCase());
  }
  if (colors.size > 25) {
    results.push(warn('ui/color-sprawl', 'low', `${colors.size} different hardcoded colors in components: no consistent palette`, { fix: 'Define colors once as design tokens (Tailwind theme or CSS variables) and reference them.' }));
  }

  const zHacks = ctx.grep([...markup, ...styles], /z-\[\d{4,}\]|z-index\s*:\s*\d{4,}|zIndex\s*:\s*\d{4,}/, { literals: true });
  results.push(...capped('ui/z-index-war', 'low', 'z-index of 1000+ is a sign of stacking hacks', 'Define a small z-index scale (e.g. 10 dropdown, 20 sticky, 50 modal) and use it everywhere.', zHacks.map((m) => ({ file: m.file, line: m.line, snippet: m.text }))));

  if (results.length === 0) results.push(pass('ui/basics', `No UI or content issues found in ${markup.length} files`));
  return results;
}
