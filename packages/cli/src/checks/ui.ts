import type { ProjectContext, SourceFile } from '../context.js';
import { type CheckResult, type Severity, pass, warn, info } from '../types.js';
import { isClientFile } from './security.js';

const MARKUP_EXT = /\.(jsx|tsx|vue|svelte|astro|html)$/i;
const STYLE_EXT = /\.(css|scss|sass|less)$/i;
const MAX_PER_RULE = 5;

const lineStarts = new WeakMap<SourceFile, number[]>();

/** 1-based line number of a character offset (line offsets are computed once per file). */
function lineAt(f: SourceFile, index: number): number {
  let starts = lineStarts.get(f);
  if (!starts) {
    starts = [0];
    for (let i = 0; i < f.content.length; i++) if (f.content.charCodeAt(i) === 10) starts.push(i + 1);
    lineStarts.set(f, starts);
  }
  let lo = 0;
  let hi = starts.length - 1;
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    if (starts[mid] <= index) lo = mid;
    else hi = mid - 1;
  }
  return lo + 1;
}

/** Report up to MAX_PER_RULE locations, then one summary line. */
function capped(id: string, severity: Severity, message: string, fix: string, hits: Array<{ file: string; line?: number; snippet?: string; detail?: string }>): CheckResult[] {
  const out = hits.slice(0, MAX_PER_RULE).map((h) => warn(id, severity, h.detail ? `${message}: ${h.detail}` : message, { file: h.file, line: h.line, snippet: h.snippet, fix }));
  if (hits.length > MAX_PER_RULE) out.push(warn(id, severity, `${message} (${hits.length - MAX_PER_RULE} more)`, { fix }));
  return out;
}

